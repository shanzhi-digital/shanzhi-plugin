#!/usr/bin/env node
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// 从 erji 仓库将 @echomind/minutes-engine + @echomind/shared (+ zod) 打包成零外部依赖的 ESM 产物
// lib/minutes-engine.mjs，使 @local/echomind 插件运行时零三方 npm 依赖。

const __dirname = dirname(fileURLToPath(import.meta.url));
const pluginRoot = resolve(__dirname, '..');
const defaultErjiRoot = resolve(pluginRoot, '../../../../erji');
const erjiRoot = resolve(process.env.ERJI_ROOT || defaultErjiRoot);
const outFile = join(pluginRoot, 'lib', 'minutes-engine.mjs');

function findEsbuild() {
  const candidates = [
    process.env.ESBUILD_DIR && join(process.env.ESBUILD_DIR, 'lib', 'main.js'),
    join(erjiRoot, 'node_modules', 'esbuild', 'lib', 'main.js'),
    resolve(erjiRoot, '..', 'upworks', 'node_modules', 'esbuild', 'lib', 'main.js'),
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate;
  }
  throw new Error('找不到 esbuild，请设置 ESBUILD_DIR 环境变量指向 esbuild 包目录。');
}

const esbuildPath = findEsbuild();
const esbuild = await import(pathToFileURL(esbuildPath).href);

const engineEntry = join(erjiRoot, 'packages', 'minutes-engine', 'src', 'index.ts');
const sharedEntry = join(erjiRoot, 'packages', 'shared', 'src', 'index.ts');
if (!existsSync(engineEntry) || !existsSync(sharedEntry)) {
  throw new Error(`未在 ${erjiRoot} 找到 EchoMind packages/minutes-engine 或 packages/shared。`);
}

let erjiCommit = 'unknown';
try {
  erjiCommit = execSync('git rev-parse HEAD', { cwd: erjiRoot, encoding: 'utf8' }).trim();
} catch {
  // Ignore when git metadata is unavailable.
}

mkdirSync(dirname(outFile), { recursive: true });

await esbuild.build({
  stdin: {
    contents: `export * from ${JSON.stringify(engineEntry)};\nexport * from ${JSON.stringify(sharedEntry)};\n`,
    resolveDir: join(erjiRoot, 'packages', 'minutes-engine'),
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  minify: false,
  outfile: outFile,
  banner: {
    js: `// Auto-generated by build/sync-engine.mjs from erji (${erjiCommit})\n// Contains @echomind/minutes-engine + @echomind/shared + zod (zero runtime npm deps).\n`,
  },
  alias: {
    '@echomind/shared': sharedEntry,
  },
});

const bytes = readFileSync(outFile).byteLength;
console.log(`Built ${outFile} (${(bytes / 1024).toFixed(1)} KB, erji=${erjiCommit.slice(0, 12)})`);
